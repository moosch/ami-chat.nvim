-- /yank and /apply: pull fenced code blocks out of the transcript. /yank copies to
-- the clipboard; /apply stages a diff against a file (sandboxed to the project root).
-- ami never writes a file here.
local T = require("tests.minitest")
local H = require("tests.helpers")
local ui = require("ami-chat.ui")

local function transcript()
  return table.concat(ui.transcript_lines(), "\n")
end

T.describe("/yank", function()
  local C = H.fresh_controller({ root = "/tmp" })
  local function seed()
    ui.clear()
    ui.append("### Advisor\n\n```lua\nlocal x = 1\nprint(x)\n```\n\nprose\n\n```\nplain\n```\n")
  end

  T.it("defaults to the last block", function()
    seed()
    C.yank_block("")
    T.eq(vim.fn.getreg('"'), "plain")
  end)
  T.it("N selects the Nth block", function()
    seed()
    C.yank_block("1")
    T.eq(vim.fn.getreg('"'), "local x = 1\nprint(x)")
  end)
  T.it("-1 selects the last block", function()
    seed()
    C.yank_block("-1")
    T.eq(vim.fn.getreg('"'), "plain")
  end)
  T.it("out of range leaves the register untouched", function()
    seed()
    vim.fn.setreg('"', "KEEP")
    C.yank_block("9")
    T.eq(vim.fn.getreg('"'), "KEEP")
    T.ok(transcript():find("no code block 9", 1, true))
  end)
  T.it("reports when there are no blocks", function()
    ui.clear()
    ui.append("just prose, no fences\n")
    C.yank_block("")
    T.ok(transcript():find("no code blocks", 1, true))
  end)
end)

T.describe("/apply", function()
  local root = vim.fn.tempname()
  vim.fn.mkdir(root, "p")
  local C = H.fresh_controller({ root = root })

  T.it("refuses a path escaping the root", function()
    ui.clear()
    ui.append("```c\nx\n```\n")
    C.apply_block("1 ../escape.c")
    T.ok(transcript():find("refusing a path outside the project root", 1, true))
    H.drain_windows()
  end)
  T.it("stages a diff against an in-root path (shown project-relative)", function()
    ui.clear()
    ui.append("```c\nx\n```\n")
    C.apply_block("1 sub/new.c")
    T.ok(transcript():find("against `sub/new.c`", 1, true))
    H.drain_windows()
  end)
  T.it("asks for a path when there is no source file", function()
    ui.clear()
    ui.append("```c\nx\n```\n")
    C.source_buf = nil
    C.apply_block("")
    T.ok(transcript():find("no target file", 1, true))
    H.drain_windows()
  end)
end)
